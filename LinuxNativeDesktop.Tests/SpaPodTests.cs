using LinuxNativeDesktop.Capture;

namespace LinuxNativeDesktop.Tests;

/// <summary>
/// The reference bytes come from tools/spa-reference.c, which builds the same pods with PipeWire's own
/// spa_pod_builder. Regenerate them with that tool if the pods change.
/// </summary>
public class SpaPodTests
{
	[Fact]
	public void EnumFormatMatchesSpaBuilder() => Assert.Equal(ReferenceEnumFormat, SpaPod.BuildVideoEnumFormat(30));

	[Fact]
	public void BuffersMatchesSpaBuilder() => Assert.Equal(ReferenceBuffers, SpaPod.BuildCpuBuffers());

	[Fact]
	public void FormatMatchesSpaBuilder() => Assert.Equal(ReferenceFormat, SpaPod.BuildVideoFormat(SpaPod.VideoBGRx, 2560, 1440));

	[Fact]
	public void ParsesFormatFromSpaBuilder()
	{
		var format = SpaPod.ParseVideoFormat(ReferenceFormat);
		Assert.Equal(new SpaPod.VideoFormat(SpaPod.VideoBGRx, 2560, 1440, false), format);
	}

	[Fact]
	public void ParsesDefaultsOutOfChoices()
	{
		// An EnumFormat holds choices; the parser takes each choice's default value.
		var format = SpaPod.ParseVideoFormat(ReferenceEnumFormat);
		Assert.Equal(new SpaPod.VideoFormat(SpaPod.VideoRGBx, 1920, 1080, false), format);
	}

	[Fact]
	public void RejectsNonFormatPods()
	{
		Assert.Null(SpaPod.ParseVideoFormat(ReferenceBuffers));
		Assert.Null(SpaPod.ParseVideoFormat([]));
		Assert.Null(SpaPod.ParseVideoFormat(ReferenceFormat.AsSpan(0, 40))); // truncated
		var hugeProperty = ReferenceFormat.ToArray();
		BitConverter.TryWriteBytes(hugeProperty.AsSpan(16 + 8), 0xFFFFFFF0u); // first property's size
		Assert.Null(SpaPod.ParseVideoFormat(hugeProperty));
	}

	[Theory]
	[InlineData(SpaPod.VideoBGRx, PixelLayout.Bgra)]
	[InlineData(SpaPod.VideoBGRA, PixelLayout.Bgra)]
	[InlineData(SpaPod.VideoRGBx, PixelLayout.Rgba)]
	[InlineData(SpaPod.VideoRGBA, PixelLayout.Rgba)]
	public void MapsOfferedFormatsToLayouts(uint format, PixelLayout layout) => Assert.Equal(layout, SpaPod.LayoutOf(format));

	[Fact]
	public void UnknownFormatHasNoLayout() => Assert.Null(SpaPod.LayoutOf(2 /* I420 */));

